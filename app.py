
from pathlib import Path

import numpy as np
import streamlit as st
import tensorflow as tf

from PIL import Image, ImageOps, UnidentifiedImageError


# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

PROJECT_DIR = Path(__file__).resolve().parent
MODEL_PATH = PROJECT_DIR / "models" / "pneumonia_model.keras"

IMAGE_SIZE = (224, 224)
CLASS_NAMES = ["NORMAL", "PNEUMONIA"]
DEFAULT_THRESHOLD = 0.50


# --------------------------------------------------
# 2. Streamlit page setup
# --------------------------------------------------

st.set_page_config(
    page_title="Chest X-Ray Classification",
    page_icon="🩻",
    layout="centered",
)

st.title("🩻 Chest X-Ray Classification")
st.write(
    "Upload a chest X-ray image to see the prediction "
    "generated by the trained deep learning model."
)

st.warning(
    "Educational demonstration only. This application is "
    "not a medical diagnostic tool. Its predictions may be "
    "incorrect and must not be used to make medical decisions."
)


# --------------------------------------------------
# 3. Load the trained model
# --------------------------------------------------

@st.cache_resource
def load_trained_model(model_path):
    return tf.keras.models.load_model(
        model_path,
        compile=False,
    )


if not MODEL_PATH.exists():
    st.error(
        "The trained model was not found. "
        "Please run train_model.py first and check the models folder."
    )
    st.stop()

try:
    model = load_trained_model(str(MODEL_PATH))
except Exception as error:
    st.error(f"Could not load the trained model: {error}")
    st.stop()


# --------------------------------------------------
# 4. Upload an image
# --------------------------------------------------

uploaded_file = st.file_uploader(
    "Choose a chest X-ray image",
    type=["jpg", "jpeg", "png"],
    help="Upload a JPG, JPEG, or PNG image.",
)


# --------------------------------------------------
# 5. Preprocess the uploaded image
# --------------------------------------------------

def preprocess_image(image):
    # Correct image orientation when EXIF metadata is available.
    image = ImageOps.exif_transpose(image)

    # The model expects three color channels.
    image = image.convert("RGB")

    # Use the same input dimensions as model training.
    image = image.resize(
        IMAGE_SIZE,
        Image.Resampling.BILINEAR,
    )

    # Keep pixel values in the 0-255 range.
    # The model's Rescaling layer converts them to [-1, 1].
    image_array = np.asarray(
        image,
        dtype=np.float32,
    )

    # Add a batch dimension: (224, 224, 3)
    # becomes (1, 224, 224, 3).
    image_array = np.expand_dims(
        image_array,
        axis=0,
    )

    return image_array


# --------------------------------------------------
# 6. Display the image and predict
# --------------------------------------------------

if uploaded_file is not None:
    try:
        image = Image.open(uploaded_file)
        image = ImageOps.exif_transpose(image).convert("RGB")

        st.subheader("Uploaded X-ray")
        st.image(
            image,
            caption="Uploaded image",
            width="stretch",
        )

        if st.button(
            "Analyze Image",
            type="primary",
            use_container_width=True,
        ):
            with st.spinner("Analyzing the image..."):
                input_array = preprocess_image(image)

                prediction = model.predict(
                    input_array,
                    verbose=0,
                )

                pneumonia_score = float(
                    np.asarray(prediction).reshape(-1)[0]
                )

                if not np.isfinite(pneumonia_score):
                    st.error(
                        "The model returned an invalid prediction."
                    )
                    st.stop()

                pneumonia_score = float(
                    np.clip(pneumonia_score, 0.0, 1.0)
                )

                normal_score = 1.0 - pneumonia_score

                if pneumonia_score >= DEFAULT_THRESHOLD:
                    predicted_class = "PNEUMONIA"
                    displayed_score = pneumonia_score
                else:
                    predicted_class = "NORMAL"
                    displayed_score = normal_score

            st.subheader("Model Prediction")

            if predicted_class == "PNEUMONIA":
                st.error("Predicted class: PNEUMONIA")
            else:
                st.success("Predicted class: NORMAL")

            col1, col2 = st.columns(2)

            with col1:
                st.metric(
                    "Normal score",
                    f"{normal_score * 100:.2f}%",
                )

            with col2:
                st.metric(
                    "Pneumonia score",
                    f"{pneumonia_score * 100:.2f}%",
                )

            st.caption(
                f"Classification threshold: {DEFAULT_THRESHOLD:.2f}"
            )

            st.progress(displayed_score)

            st.info(
                "These scores are model outputs, not clinically "
                "validated probabilities or diagnostic confidence. "
                "The classification depends on the selected threshold."
            )

    except (UnidentifiedImageError, OSError, ValueError):
        st.error(
            "The uploaded file could not be processed as an image. "
            "Please try a valid JPG, JPEG, or PNG file."
        )

else:
    st.info(
        "Upload an image to begin. The model will run when "
        "you click Analyze Image."
    )


# --------------------------------------------------
# 7. Project information
# --------------------------------------------------

with st.expander("About this project"):
    st.write(
        "This educational project uses transfer learning with "
        "MobileNetV2 to classify chest X-ray images into two "
        "dataset categories: NORMAL and PNEUMONIA."
    )

    st.write(
        "The model was trained using a chest X-ray dataset and "
        "evaluated on a separate test split. Its results do not "
        "establish clinical safety or suitability for patient care."
    )
